marks = input("Введіть оцінки студентів: ").split() #зчитуєм введені оцінки
count_A = 0
for mark in marks: #перевіряєм кожні оцінку в списку
    if mark == 'A': #провіряєм чи є поточною оцінкою А, якщо так збільшуєм на 1
        count_A += 1
fraction = count_A / len(marks) #знаходим відношення
print(f"{fraction:.2f}") #виводим результат(два знаки після коми)